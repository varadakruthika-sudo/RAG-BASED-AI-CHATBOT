print("Libraries imported successfully!")

def load_and_split_pdf(pdf_path):

    loader = PyMuPDFLoader(pdf_path)

    documents = loader.load()

    splitter = RecursiveCharacterTextSplitter(
        chunk_size=500,
        chunk_overlap=100
    )

    chunks = splitter.split_documents(documents)

    return chunks

def create_vector_store(chunks):

    embeddings = HuggingFaceEmbeddings(
        model_name="sentence-transformers/all-MiniLM-L6-v2"
    )

    vector_store = FAISS.from_documents(
        chunks,
        embeddings
    )

    return vector_store

from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser


llm = ChatGoogleGenerativeAI(
    model="gemini-3.5-flash",
    temperature=0
)


prompt = ChatPromptTemplate.from_template("""
Answer the question using only the given context.

If the answer is not present in the context,
say that the information is not available in the PDF.

Context:
{context}

Question:
{question}

Answer:
""")

print("Gemini model initialized successfully!")

def create_rag_chain(vector_store):

    retriever = vector_store.as_retriever(
        search_kwargs={"k": 2}
    )

    chain = prompt | llm | StrOutputParser()

    def retrieve_and_answer(question):

        try:
            documents = retriever.invoke(question)

            if not documents:
                return "No relevant information found in the PDF."

            context = "\n\n".join(
                doc.page_content for doc in documents
            )

            answer = chain.invoke({
                "context": context,
                "question": question
            })

            return answer

        except Exception as e:
            print("QUESTION ANSWERING ERROR:", repr(e))
            return f"Error details: {str(e)}"

    return retrieve_and_answer

vector_store = None
rag_function = None

def process_pdf(pdf_path):

    global vector_store, rag_function

    try:
        if pdf_path is None:
            return "Please upload a PDF."

        chunks = load_and_split_pdf(pdf_path)

        if not chunks:
            return "No readable text found in PDF."

        vector_store = create_vector_store(chunks)

        rag_function = create_rag_chain(vector_store)

        return "PDF processed successfully! Ask your question."

    except Exception as e:
        print("PDF PROCESSING ERROR:", repr(e))
        return f"Processing error: {str(e)}"


def ask_question(question):

    if rag_function is None:
        return "Please upload and process a PDF first."

    if not question.strip():
        return "Please enter a question."

    return rag_function(question)

